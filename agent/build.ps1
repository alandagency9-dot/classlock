# Builds the ClassLock laptop programs with the C# compiler that ships with
# Windows (.NET Framework 4.8). Nothing needs to be installed.
#
#   powershell -ExecutionPolicy Bypass -File build.ps1
#
# Reads config.json (copy config.example.json). Output:
#   dist\ClassLockSetup.exe   the only file you copy to the laptops
#   dist\ClassLock.exe        (already inside the setup file)
# Without config.json only the tests are built and run.

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$obj = Join-Path $root 'obj'
$dist = Join-Path $root 'dist'
New-Item -ItemType Directory -Force $obj, $dist | Out-Null

$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { throw "C# compiler not found at $csc" }

$version = '1.2.0'
$configPath = Join-Path $root 'config.json'
$haveConfig = Test-Path $configPath
if ($haveConfig) {
    $cfg = Get-Content $configPath -Raw | ConvertFrom-Json
    $url = [string]$cfg.supabaseUrl
    $key = [string]$cfg.anonKey
    if ($url -notmatch '^https://[a-z0-9-]+\.supabase\.co/?$') { throw "config.json: supabaseUrl must look like https://xxxx.supabase.co" }
    if ($key.Length -lt 30 -or $key -match 'your-anon-key') { throw "config.json: anonKey is missing" }
} else {
    Write-Host 'config.json not found: building and running tests only.' -ForegroundColor Yellow
    $url = 'https://example.supabase.co'
    $key = 'test-key'
}

function Escape([string]$s) { $s.Replace('\', '\\').Replace('"', '\"') }
@"
// Generated by build.ps1. Do not edit.
namespace ClassLock
{
    public static class BuildConfig
    {
        public const string SupabaseUrl = "$(Escape $url)";
        public const string AnonKey = "$(Escape $key)";
        public const string Version = "$version";
    }
}
"@ | Set-Content -Encoding UTF8 (Join-Path $obj 'BuildConfig.cs')

$refs = @(
    '/r:System.dll', '/r:System.Core.dll', '/r:System.ServiceProcess.dll', '/r:System.Web.Extensions.dll',
    '/r:System.Net.Http.dll', '/r:System.Windows.Forms.dll', '/r:System.Drawing.dll'
)
$core = @((Join-Path $root 'src\*.cs'), (Join-Path $obj 'BuildConfig.cs'))

function Compile([string[]]$csArgs) {
    & $csc /nologo /optimize+ /warnaserror+ /platform:anycpu @csArgs
    if ($LASTEXITCODE -ne 0) { throw "Compile failed: $($csArgs -join ' ')" }
}

# 1. Tests (console program) - always.
$tests = Join-Path $obj 'ClassLockTests.exe'
Compile (@('/target:exe', "/out:$tests") + $refs + $core + (Join-Path $root 'tests\Tests.cs'))
& $tests
if ($LASTEXITCODE -ne 0) { throw "$LASTEXITCODE test(s) failed" }

if (-not $haveConfig) { exit 0 }

# 2. The laptop app + service.
$app = Join-Path $dist 'ClassLock.exe'
Compile (@('/target:winexe', "/out:$app", "/win32manifest:$(Join-Path $root 'app\ClassLock.manifest')") +
    $refs + $core + (Join-Path $root 'app\*.cs'))

# 3. The setup program, with ClassLock.exe inside it.
$setup = Join-Path $dist 'ClassLockSetup.exe'
Compile (@('/target:winexe', "/out:$setup", "/win32manifest:$(Join-Path $root 'setup\Setup.manifest')",
    "/resource:$app,ClassLock.exe") + $refs +
    @((Join-Path $root 'setup\Setup.cs'), (Join-Path $root 'src\ChromePolicy.cs'),
      (Join-Path $root 'src\LockRules.cs'), (Join-Path $root 'src\Json.cs')))

Write-Host "Built $setup" -ForegroundColor Green
